// 5. YOUTUBE API
// ============================================================

function loadYouTubeAPI() {

  if (
    window.YT &&
    window.YT.Player
  ) {

    onYouTubeIframeAPIReady();

    return;
  }


  const existingScript =
    document.querySelector(
      'script[src="https://www.youtube.com/iframe_api"]'
    );

  if (existingScript) {
    return;
  }


  const tag =
    document.createElement("script");

  tag.src =
    "https://www.youtube.com/iframe_api";


  const firstScriptTag =
    document.getElementsByTagName("script")[0];


  if (
    firstScriptTag &&
    firstScriptTag.parentNode
  ) {

    firstScriptTag.parentNode.insertBefore(
      tag,
      firstScriptTag
    );

  } else {

    document.head.appendChild(tag);

  }

}


// ============================================================
// 6. YOUTUBE PLAYER READY
// ============================================================

window.onYouTubeIframeAPIReady = function () {

  const host =
    document.getElementById(
      "yt-audio-player"
    );


  if (!host) {

    console.warn(
      "YouTube player element not found."
    );

    return;
  }


  ytPlayer =
    new YT.Player(
      "yt-audio-player",
      {

        playerVars: {

          autoplay: 0,

          controls: 0,

          disablekb: 1,

          fs: 0,

          iv_load_policy: 3,

          modestbranding: 1,

          rel: 0,

          playsinline: 1,

          origin: window.location.origin

        },


        events: {

          onReady: onPlayerReady,

          onStateChange:
            onPlayerStateChange,

          onError:
            onPlayerError

        }

      }
    );

};


// ============================================================
// 7. PLAYER READY
// ============================================================

function onPlayerReady() {

  updateTrackUI(
    currentTrackIndex
  );

}


// ============================================================
// 8. PLAYER STATE
// ============================================================

function onPlayerStateChange(event) {


  if (
    event.data ===
    YT.PlayerState.PLAYING
  ) {

    isPlaying = true;

    updatePlayBtnUI(true);

    startSeekLoop();


    // Successful playback.
    // Reset error counters.

    trackRetryCount = 0;

    attemptedTracks.clear();

  }


  else if (
    event.data ===
    YT.PlayerState.PAUSED
  ) {

    isPlaying = false;

    updatePlayBtnUI(false);

    stopSeekLoop();

  }


  else if (
    event.data ===
    YT.PlayerState.ENDED
  ) {

    nextTrack();

  }


  else if (
    event.data ===
    YT.PlayerState.BUFFERING
  ) {

    // IMPORTANT:
    //
    // Buffering is NOT an error.
    //
    // Never skip a song just because
    // YouTube is buffering.

  }

}


// ============================================================
// 9. YOUTUBE ERROR HANDLER
// ============================================================

function onPlayerError(event) {

  const errorCode =
    Number(event?.data);


  const failedIndex =
    currentTrackIndex;


  console.warn(
    "YouTube error:",
    errorCode,
    playlist[failedIndex]?.title
  );


  // Retry only once.

  if (
    trackRetryCount <
    MAX_RETRIES_PER_TRACK
  ) {

    trackRetryCount++;


    const retryToken =
      trackLoadToken;


    setTimeout(() => {


      // Another track was loaded.
      // Cancel this retry.

      if (
        retryToken !==
        trackLoadToken
      ) {

        return;
      }


      if (!ytPlayer) {
        return;
      }


      loadAndPlayTrack(
        failedIndex,
        {
          keepRetryCount: true
        }
      );


    }, TRACK_ERROR_WAIT_MS);


    return;
  }


  // Retry failed.
  // Move safely to next track.

  skipFailedTrack(
    failedIndex
  );

}


// ============================================================
// 10. SAFE FAILED TRACK SKIP
// ============================================================

function skipFailedTrack(
  failedIndex
) {


  if (advanceLock) {
    return;
  }


  advanceLock = true;


  attemptedTracks.add(
    failedIndex
  );


  stopSeekLoop();


  setTimeout(() => {


    const nextIndex =
      findNextPlayableCandidate(
        failedIndex
      );


    advanceLock = false;


    if (
      nextIndex === -1
    ) {


      console.warn(
        "All tracks attempted. Resetting queue."
      );


      attemptedTracks.clear();

      trackRetryCount = 0;


      loadAndPlayTrack(
        (failedIndex + 1) %
        playlist.length
      );


      return;
    }


    trackRetryCount = 0;


    loadAndPlayTrack(
      nextIndex
    );


  }, 300);

}


// ============================================================
// 11. FIND NEXT TRACK
// ============================================================

function findNextPlayableCandidate(
  startIndex
) {


  for (
    let offset = 1;
    offset <= playlist.length;
    offset++
  ) {


    const index =
      (
        startIndex +
        offset
      ) %
      playlist.length;


    if (
      !attemptedTracks.has(index)
    ) {

      return index;

    }

  }


  return -1;

}


// ============================================================
// 12. POPULATE PLAYLIST DROPDOWN
// ============================================================

function populatePlaylistDropdown() {


  const selectEl =
    document.getElementById(
      "playlist-select"
    );


  if (!selectEl) {
    return;
  }


  selectEl.innerHTML = "";


  playlist.forEach(
    (item, index) => {


      const option =
        document.createElement(
          "option"
        );


      option.value = index;


      option.innerText =
        `${index + 1}. ${item.title} — ${item.artist}`;


      selectEl.appendChild(
        option
      );

    }
  );


  selectEl.value =
    currentTrackIndex;


  selectEl.onchange =
    (event) => {


      const selectedIndex =
        parseInt(
          event.target.value,
          10
        );


      loadAndPlayTrack(
        selectedIndex
      );

    };

}


// ============================================================
// 13. UPDATE TRACK UI
// ============================================================

function updateTrackUI(index) {


  const track =
    playlist[index];


  if (!track) {
    return;
  }


  const titleEl =
    document.getElementById(
      "track-title"
    );


  const artistEl =
    document.getElementById(
      "track-artist"
    );


  const artEl =
    document.getElementById(
      "track-art"
    );


  const selectEl =
    document.getElementById(
      "playlist-select"
    );


  if (titleEl) {

    titleEl.innerText =
      track.title;

  }


  if (artistEl) {

    artistEl.innerText =
      track.artist;

  }


  if (selectEl) {

    selectEl.value =
      index;

  }


  if (artEl) {


    artEl.style.transition =
      "opacity 0.2s ease";


    artEl.style.opacity =
      "0.3";


    const uiIndex =
      index;


    setTimeout(() => {


      // Do not overwrite artwork
      // if another song loaded.

      if (
        currentTrackIndex !==
        uiIndex
      ) {

        return;
      }


      artEl.src =
        track.art;


      artEl.style.opacity =
        "1";


    }, 120);

  }

}


// ============================================================
// 14. LOAD AND PLAY TRACK
// ============================================================

function loadAndPlayTrack(
  index,
  options = {}
) {


  if (
    !Number.isInteger(index) ||
    index < 0 ||
    index >= playlist.length
  ) {

    return;
  }


  currentTrackIndex =
    index;


  trackLoadToken++;


  if (
    !options.keepRetryCount
  ) {

    trackRetryCount = 0;

  }


  updateTrackUI(
    currentTrackIndex
  );


  const track =
    playlist[
      currentTrackIndex
    ];


  if (
    !ytPlayer ||
    typeof ytPlayer.loadVideoById !==
    "function"
  ) {


    console.warn(
      "YouTube player not ready."
    );


    updatePlayBtnUI(
      false
    );


    return;
  }


  attemptedTracks.delete(
    currentTrackIndex
  );


  try {


    ytPlayer.loadVideoById({

      videoId:
        track.youtubeId,

      suggestedQuality:
        "small"

    });


  }

  catch (error) {


    console.warn(
      "Unable to load YouTube video:",
      error
    );


    onPlayerError({
      data: 5
    });

  }

}


// ============================================================
// 15. PLAY / PAUSE
// ============================================================

function togglePlay() {


  if (
    !ytPlayer ||
    typeof ytPlayer.getPlayerState !==
    "function"
  ) {


    console.warn(
      "YouTube player is not ready."
    );


    return;
  }


  const state =
    ytPlayer.getPlayerState();


  if (
    state ===
    YT.PlayerState.PLAYING
  ) {


    ytPlayer.pauseVideo();


  } else {


    ytPlayer.playVideo();

  }

}


// ============================================================
// 16. NEXT
// ============================================================

function nextTrack() {


  if (advanceLock) {
    return;
  }


  trackRetryCount = 0;


  currentTrackIndex =
    (
      currentTrackIndex +
      1
    ) %
    playlist.length;


  loadAndPlayTrack(
    currentTrackIndex
  );

}


// ============================================================
// 17. PREVIOUS
// ============================================================

function prevTrack() {


  if (advanceLock) {
    return;
  }


  trackRetryCount = 0;


  currentTrackIndex =
    (
      currentTrackIndex -
      1 +
      playlist.length
    ) %
    playlist.length;


  loadAndPlayTrack(
    currentTrackIndex
  );

}


// ============================================================
// 18. PLAY BUTTON UI
// ============================================================

function updatePlayBtnUI(
  playing
) {


  const playBtn =
    document.getElementById(
      "play-btn"
    );


  const trackArtEl =
    document.getElementById(
      "track-art"
    );


  if (playBtn) {


    playBtn.innerHTML =
      playing
        ? "❚❚"
        : "▶";


    playBtn.style.color =
      "#09090b";

  }


  if (trackArtEl) {


    if (playing) {

      trackArtEl.classList.remove(
        "vinyl-paused"
      );

    } else {

      trackArtEl.classList.add(
        "vinyl-paused"
      );

    }

  }

}


